-- The pattern `\227[\136-\139][\128-\191]` matches exactly U+3200..U+32FF
-- in UTF-8 (E3 88..8B 80..BF). One gsub scans the whole line; each match
-- is looked up in MAP, and codepoints with no decomposition (a few
-- assigned but identity-mapped, plus the unassigned holes) fall through
-- unchanged.
---@param text string
---@return string
function M.convert(text)
  return (
    text:gsub("\227[\136-\139][\128-\191]", function(m)
      return MAP[m] or m
    end)
  )
end

return M


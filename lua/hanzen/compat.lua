-- The pattern `\227[\140-\143][\128-\191]` matches exactly U+3300..U+33FF
-- in UTF-8 (E3 8C..8F 80..BF). One gsub scans the whole line; each match
-- is looked up in MAP, and unknown sequences (none in this block today,
-- but defensively) fall through unchanged.
---@param text string
---@return string
function M.convert(text)
  return (
    text:gsub("\227[\140-\143][\128-\191]", function(m)
      return MAP[m] or m
    end)
  )
end

return M

